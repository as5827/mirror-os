def is_nvc(tone):
    return (tone or "").strip().lower() == "nvc"


def audit(text):
    """体检：数「评判性」痕迹。改提示词后用同一批问题跑前后对比。"""
    t = text or ""
    judgment = re.findall(r"你(?:总是|从不|又|老是|根本|就是|压根)", t)
    should = re.findall(r"(?:你应该|你必须|你得)", t)
    label = re.findall(r"(?:型人格|依恋|人格障碍|你就是个)", t)
    return {
        "chars": len(t),
        "概括": len(judgment),
        "命令式": len(should),
        "贴标签": len(label),
        "观察句": len(re.findall(r"这周|上周|这两天|\d+\s*(?:条|次|天|小时)", t)),
    }
