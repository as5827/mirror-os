"""共情判定：先判断「这轮该不该先安慰」，再决定用什么体例回答。

为什么要单独一层而不是在提示词里写「必要时先共情」：
  「必要时」对模型等于「随便」，结果要么永远不安慰，要么永远先来一段空心套话。
  这里用可解释的词表打分，得出一档 level，把模糊判断变成确定性输入。

level：
  0  无情绪信号        直接分析
  1  轻度负面          一句话确认，然后立刻分析
  2  明显痛苦          先共情 2–4 句，把控制权交回他，再分析
  3  强痛苦/自我否定   同上，但降低分析强度，先问要不要现在谈
  crisis 自伤/轻生信号  安全优先：共情 + 明确建议求助，不进入分析

重要：这不做心理诊断，只做「措辞体例」的选择。真正的判断留给模型和用户。
"""
