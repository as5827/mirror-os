"""Agent Skills 兼容层。

格式照搬 anthropics/skills 的公开规范（Skill = 一个文件夹 + SKILL.md，
YAML frontmatter 只有 name 与 description 两个必填字段）：
    https://github.com/anthropics/skills

为什么要照搬而不是自创：这样你的 skill 是可移植的纯文本，
以后想在其他 agent 里复用、或者从社区拿现成的 skill 丢进来，都不用改格式。

关键设计——渐进披露（progressive disclosure）：
  系统提示里只放 skill 的 name + description（每个约 30 字），不放正文。
  只有你真正选中某个 skill 时，才把它的正文注入。
  这样挂 50 个 skill 也只多花 1500 字，长对话不会被技能库撑爆。
"""
import os
import re

BASE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SKILLS_DIR = os.path.join(BASE_DIR, "skills")

FM_RE = re.compile(r"^---\s*\r?\n(.*?)\r?\n---\s*\r?\n?(.*)$", re.S)


def parse_skill_md(text):
    """解析 SKILL.md。返回 (meta dict, body str)。不依赖 yaml 库。"""
    m = FM_RE.match(text.strip())
    if not m:
        return {}, text.strip()
    raw_meta, body = m.group(1), m.group(2)
    meta = {}
    for line in raw_meta.splitlines():
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        if ":" not in line:
            continue
        k, v = line.split(":", 1)
        k = k.strip()
        v = v.strip().strip('"').strip("'")
        if k:
            meta[k] = v
    return meta, body.strip()


def load_all():
    """扫描 skills 目录，返回 [{name,description,body,path}]。"""
    out = []
    if not os.path.isdir(SKILLS_DIR):
        return out
    for entry in sorted(os.listdir(SKILLS_DIR)):
        d = os.path.join(SKILLS_DIR, entry)
        if not os.path.isdir(d):
            continue
        f = os.path.join(d, "SKILL.md")
        if not os.path.exists(f):
            continue
        try:
            with open(f, "r", encoding="utf-8") as fh:
                text = fh.read()
        except OSError:
            continue
        meta, body = parse_skill_md(text)
        name = (meta.get("name") or entry).strip()
        out.append({
            "name": name,
            "description": (meta.get("description") or "").strip(),
            "body": body,
            "path": f,
            "dir": d,
        })
    return out


def get(name):
    for s in load_all():
        if s["name"] == name:
            return s
    return None


def catalog_block():
    """只含 name + description 的清单，塞进系统提示。"""
    items = [s for s in load_all() if s["description"]]
    if not items:
        return ""
    lines = ["【可用的 skill（只列出用途；你没有它们的正文，不要假装知道细节）】"]
    for s in items:
        lines.append(f"- {s['name']}：{s['description']}")
    return "\n".join(lines)


def body_block(name):
    """选中某个 skill 时，返回它的正文。"""
    s = get(name)
    if not s or not s["body"]:
        return ""
    return (f"【已启用的 skill：{s['name']}】\n"
            f"以下是你必须遵循的作业规程，与通用规则冲突时以它为准：\n\n{s['body']}")


