# -*- coding: utf-8 -*-
"""话术层：他问「这句话该怎么说」时，按情境给出得体、可照说的原话。

为什么要单独一层（而不是靠模型自由发挥）：
  「怎么说比较好」这种问题，模型默认会给一堆原则（「要真诚」「要换位思考」），
  而他要的是**能直接照说的一句话**。原则是废话，原话才有用。

  另一层原因：得体与否取决于三个可判断的东西——关系的距离、事情的重量、他要的结果。
  这三样不写清楚，产出的必然是通用套话。

与 comfort.py 的分工：
  comfort  管「这段对话用什么体例」（先安慰还是先分析）
  phrasing 管「具体这句话怎么说出口」（产出可照说的原话）
"""
import re

# 他在求话术的信号
ASK_PATTERNS = [
    "怎么回", "怎么回复", "怎么说", "怎么讲", "怎么开口", "怎么拒绝", "怎么跟",
    "该说什么", "该怎么说", "话术", "帮我想句", "怎么说比较好", "怎么表达",
    "措辞", "怎么说才", "怎么提", "怎么道歉", "怎么问", "怎么跟他说", "怎么跟她说",
    "要不要说", "我该怎么讲", "怎么回应", "怎么安慰", "怎么劝", "怎么哄",
    "怎么关心", "怎么回绝", "怎么推", "怎么说出口", "怎么沟通",
]

# 情境类型：关键词 -> 类型（用于挑温暖度/直接度配比）
SITUATIONS = {
    "拒绝": ["拒绝", "推掉", "不答应", "不想去", "借钱", "帮忙", "婉拒", "回绝"],
    "道歉": ["道歉", "认错", "我错了", "赔礼", "对不起"],
    "请求": ["请求", "帮我", "麻烦", "请人", "求助", "借"],
    "不满": ["不满", "抗议", "生气", "意见", "投诉"],
    "安慰": ["安慰", "失恋", "难过", "低落", "崩溃", "哭"],
    "修复": ["修复", "和好", "冷战", "闹僵", "疏远"],
    "负反馈": ["指出", "批评", "反馈", "提醒他", "做得不好", "方案有问题",
              "有问题", "不满意", "不得罪", "委婉"],
    "边界": ["边界", "白嫖", "索取", "占便宜", "降级", "断联"],
    "感谢": ["感谢", "谢谢", "肯定", "夸奖"],
    "上位者": ["老板", "领导", "导师", "上级", "老师", "面试官"],
}

# 每种情境的默认配比：温暖度（1-5）、直接度（1-5）
DEFAULT_RATIO = {
    "拒绝": (3, 4),
    "道歉": (4, 4),
    "请求": (3, 3),
    "不满": (3, 4),
    "安慰": (5, 1),
    "修复": (4, 3),
    "负反馈": (3, 4),
    "边界": (2, 5),
    "感谢": (4, 3),
    "上位者": (3, 3),
    "通用": (3, 3),
}


def detect(text):
    """判断是不是在求话术，以及属于哪类情境。"""
    t = (text or "").replace(" ", "")
    ask = any(p in t for p in ASK_PATTERNS)
    hits = []
    for name, kws in SITUATIONS.items():
        if any(k in t for k in kws):
            hits.append(name)
    # 安慰/拒绝这类更具体的优先于「上位者」这种关系标签
    kind = hits[0] if hits else "通用"
    for prefer in ("安慰", "道歉", "修复", "边界", "拒绝", "负反馈", "感谢", "请求", "不满"):
        if prefer in hits:
            kind = prefer
            break
    else:
        if "上位者" in hits:
            kind = "上位者"
    return {"ask": ask, "kind": kind, "hits": hits}


BLOCK = """【本轮他在求「这句话怎么说」——按下面的规程产出原话，不要给原则】

0. 先做一句定位（只一句，不要展开成分析）：
   用「场景 = 关系 + 你要的结果」的格式说清。例：「这是对同事的拒绝，你要的是推掉这件事又不撕破脸。」

1. 定语气配比：温暖度 {warm}/5、直接度 {direct}/5（情境判定为「{kind}」）。
   配比的含义：
   - 温暖度高 = 先确认对方的处境或感受，再谈事；
   - 直接度高 = 把结论放在第一句，不铺垫、不解释理由；
   - 两者不矛盾：可以「第一句直接 + 后半句给台阶」。

2. 产出**两版原话**，都必须是可直接复制照说的完整句子，不是要点：
   - **A 版（偏暖）**：语气更软、给对方台阶。
   - **B 版（偏直）**：把结论摆明、少铺垫。
   两版都要满足：
   - 主语是「我」，不是「你」（「我这两天排满了」而不是「你怎么老找我」）
   - 不解释理由（解释 = 给对方反驳的入口），除非这一版明确要解释
   - **禁止任何模糊承诺**：「我看看」「我尽量」「有机会」「下次」「到时候」「再说吧」——
     这些会被对方当成半答应，等于没拒绝
   - 不用书面语（「予以」「务必」「敬请」一律删掉）

3. 给一句**风险预判**：这句话最可能被如何解读，以及对方可能的三种反应里你该防哪种。

4. 给一句**接续**：如果对方追问或施压，第二句说什么。

禁止（这几条踩过坑，务必遵守）：
- 给「要真诚沟通」「要换位思考」这类原则；
- 用形容词充数（「温柔地」「坚定地」）；
- 三版以上（选不过来等于没给）；
- **把内部判断写进回复**：不要报「温暖度 3/5、直接度 4/5」这类配比数字；
  不要汇报「两版的主语都是『我』」「都没附加补偿」这类清单勾选——
  那是给你自己看的检查表，不是给他说的话；
- 把流程标题写进正文。
"""

WARM_RULES = """【温暖来自具体，不来自形容词】这条比什么都重要：
- ❌「你真的辛苦了，要好好照顾自己」——空话，对方感觉不到
- ✅「你连续三周每天加班到十一点，还替我垫了那份报告——这不是辛苦，是被掏空」
判据：如果你把这句话里的形容词去掉，还剩具体事实，它就是有效的；
     如果去掉后什么都不剩，那就是套话，删掉重写。
"""


def instruction(text):
    """返回 (注入块, 元信息)。不是求话术时返回 (None, meta)。"""
    d = detect(text)
    if not d["ask"]:
        return None, d
    warm, direct = DEFAULT_RATIO.get(d["kind"], DEFAULT_RATIO["通用"])
    block = BLOCK.format(warm=warm, direct=direct, kind=d["kind"])
    # 温暖来自具体：这是「让人感觉温暖」最关键的一条，所以每轮都注入，
    # 不只安慰场景——拒绝、指问题、道歉同样容易说成空话。
    block += "\n" + WARM_RULES
    return block, {**d, "warm": warm, "direct": direct}
